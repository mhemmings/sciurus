package model

import (
	"fmt"
	"slices"
	"strings"
	"time"

	"vitess.io/vitess/go/vt/sqlparser"
)

// identifier quotes a SQL identifier independently of SQL keywords and names.
func identifier(value string) string { return "`" + strings.ReplaceAll(value, "`", "``") + "`" }

// literal delegates MySQL string escaping to the parser's canonical formatter.
func literal(value string) string { return sqlparser.String(sqlparser.NewStrLiteral(value)) }

// Generate emits a complete create-only schema. A zero time suppresses the
// timestamp; otherwise it is the only clock-dependent line. No database is used.
func Generate(document *Document, generatedAt time.Time) ([]byte, error) {
	err := Validate(document)
	if err != nil {
		return nil, err
	}
	var sql strings.Builder
	if !generatedAt.IsZero() {
		fmt.Fprintf(&sql, "-- Generated at %s\n", generatedAt.UTC().Format(time.RFC3339Nano))
	}
	sql.WriteString("-- Generated by Sciurus. MySQL 8.0+; apply to an empty database.\n\n")
	sql.WriteString("SET @OLD_UNIQUE_CHECKS=@@UNIQUE_CHECKS, UNIQUE_CHECKS=0;\nSET @OLD_FOREIGN_KEY_CHECKS=@@FOREIGN_KEY_CHECKS, FOREIGN_KEY_CHECKS=0;\nSET @OLD_SQL_MODE=@@SQL_MODE, SQL_MODE='ONLY_FULL_GROUP_BY,STRICT_TRANS_TABLES,NO_ZERO_IN_DATE,NO_ZERO_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION';\n\n")
	// Tables are sorted for stable output after explorer reordering. Column,
	// index and constraint order remains explicit and meaningful in the model.
	tables := slices.Clone(document.Tables)
	slices.SortFunc(tables, func(a, b Table) int { return strings.Compare(a.Name, b.Name) })
	for _, table := range tables {
		sql.WriteString(tableSQL(document, &table))
		sql.WriteString(";\n\n")
	}
	sql.WriteString("SET SQL_MODE=@OLD_SQL_MODE;\nSET FOREIGN_KEY_CHECKS=@OLD_FOREIGN_KEY_CHECKS;\nSET UNIQUE_CHECKS=@OLD_UNIQUE_CHECKS;\n")
	return []byte(sql.String()), nil
}

// tableSQL renders validated model fields in a fixed order. Disabling FK checks
// around creation permits real schemas containing circular relationships.
func tableSQL(document *Document, table *Table) string {
	parts := []string{}
	columns := map[string]string{}
	for _, column := range table.Columns {
		columns[column.ID] = column.Name
		definition := identifier(column.Name) + " " + column.Type
		if column.Charset != "" {
			definition += " CHARACTER SET " + column.Charset
		}
		if column.Collation != "" {
			definition += " COLLATE " + column.Collation
		}
		if column.Generated != "" {
			definition += " GENERATED ALWAYS AS (" + column.Generated + ")"
			if column.Stored {
				definition += " STORED"
			} else {
				definition += " VIRTUAL"
			}
		}
		if column.Nullable {
			definition += " NULL"
		} else {
			definition += " NOT NULL"
		}
		if column.Default != nil {
			definition += " DEFAULT " + *column.Default
		}
		if column.OnUpdate != "" {
			definition += " ON UPDATE " + column.OnUpdate
		}
		if column.AutoIncrement {
			definition += " AUTO_INCREMENT"
		}
		if column.Invisible {
			definition += " INVISIBLE"
		}
		if column.Comment != "" {
			definition += " COMMENT " + literal(column.Comment)
		}
		parts = append(parts, definition)
	}
	for _, index := range table.Indexes {
		definition := ""
		switch index.Kind {
		case "PRIMARY":
			definition = "PRIMARY KEY"
		case "UNIQUE":
			definition = "UNIQUE INDEX " + identifier(index.Name)
		case "FULLTEXT", "SPATIAL":
			definition = index.Kind + " INDEX " + identifier(index.Name)
		default:
			definition = "INDEX " + identifier(index.Name)
		}
		keys := []string{}
		for _, part := range index.Columns {
			key := identifier(columns[part.Column])
			if part.Length > 0 {
				key += fmt.Sprintf("(%d)", part.Length)
			}
			if part.Descending {
				key += " DESC"
			}
			keys = append(keys, key)
		}
		definition += " (" + strings.Join(keys, ", ") + ")"
		if index.Invisible {
			definition += " INVISIBLE"
		}
		if index.Comment != "" {
			definition += " COMMENT " + literal(index.Comment)
		}
		parts = append(parts, definition)
	}
	for _, foreignKey := range table.ForeignKeys {
		var target *Table
		for i := range document.Tables {
			if document.Tables[i].ID == foreignKey.ReferencedTable {
				target = &document.Tables[i]
				break
			}
		}
		keys, references := []string{}, []string{}
		for _, id := range foreignKey.Columns {
			keys = append(keys, identifier(columns[id]))
		}
		for _, id := range foreignKey.ReferencedColumns {
			for _, column := range target.Columns {
				if column.ID == id {
					references = append(references, identifier(column.Name))
					break
				}
			}
		}
		definition := "CONSTRAINT " + identifier(foreignKey.Name) + " FOREIGN KEY (" + strings.Join(keys, ", ") + ")\n    REFERENCES " + identifier(target.Name) + " (" + strings.Join(references, ", ") + ")"
		if foreignKey.OnDelete != "" {
			definition += " ON DELETE " + foreignKey.OnDelete
		}
		if foreignKey.OnUpdate != "" {
			definition += " ON UPDATE " + foreignKey.OnUpdate
		}
		parts = append(parts, definition)
	}
	for _, check := range table.Checks {
		definition := "CONSTRAINT " + identifier(check.Name) + " CHECK (" + check.Expression + ")"
		if check.Enforced != nil && !*check.Enforced {
			definition += " NOT ENFORCED"
		}
		parts = append(parts, definition)
	}
	sql := "CREATE TABLE " + identifier(table.Name) + " (\n  " + strings.Join(parts, ",\n  ") + "\n) ENGINE=InnoDB"
	charset, collation := table.Charset, table.Collation
	if charset == "" && collation == "" {
		charset = document.Charset
		collation = document.Collation
	}
	if charset != "" {
		sql += " DEFAULT CHARACTER SET=" + charset
	}
	if collation != "" {
		sql += " COLLATE=" + collation
	}
	if table.Comment != "" {
		sql += " COMMENT=" + literal(table.Comment)
	}
	return sql
}
